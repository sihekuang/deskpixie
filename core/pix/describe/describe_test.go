func TestCleanRefusesMessageFragments(t *testing.T) {
	for _, s := range []string{`<agent-message from="a91706fc445c4c179"> [Subagent`, "<task-notification> done", "[Subagent hand-back] x"} {
		if got := Clean(s); got != "" {
			t.Errorf("Clean(%q) = %q", s, got)
		}
	}
	if got := Clean("fix <div> layout"); got != "fix <div> layout" {
		t.Fatalf("a tag inside a task is fine: %q", got)
	}
}
